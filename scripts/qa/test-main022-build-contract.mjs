import fs from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const script=fs.readFileSync(path.join(root,'方案/验收记录/录音修复/PI调度/MAIN-022-编译.ps1'),'utf8');
assert.match(script, /\[string\]\$TargetDirectory\s*=\s*''/);
assert.match(script, /TargetDirectory must be new/);
assert.match(script, /\$TargetDirectory\s*=\s*Join-Path \$env:SystemDrive "mt-build\\\$Batch"/);
assert.match(script, /TargetDirectory is too long for the MSVC toolchain/);
assert.match(script, /\$env:CMAKE_C_FLAGS_RELEASE\s*=\s*'\/O2 \/Ob2 \/DNDEBUG \/utf-8'/);
assert.match(script, /\$env:CMAKE_CXX_FLAGS_RELEASE\s*=\s*'\/O2 \/Ob2 \/DNDEBUG \/utf-8'/);
assert.doesNotMatch(script, /\$env:CMAKE_GENERATOR\s*=/);
assert.doesNotMatch(script, /\$env:CMAKE_GENERATOR_PLATFORM\s*=/);
assert.match(script, /\$env:CARGO_TARGET_DIR\s*=\s*\$taskTargetDirectory/);
assert.match(script, /prepare-tauri-sidecars\.ps1/);
assert.match(script, /-TargetDirectory \(Join-Path \$taskTargetDirectory 'tauri-sidecars'\)/);
assert.match(script, /CMAKE_C_FLAGS_RELEASE/);
assert.match(script, /CMakeCache\.txt/);
assert.match(script, /CL\.command\.1\.tlog/);
assert.match(script, /\/O2/);
assert.match(script, /\/Od/);
assert.match(script, /Expected exactly one fresh whisper native build root/);
assert.match(script, /Built client is missing/);
assert.doesNotMatch(script, /Get-FileHash -LiteralPath 'target\/release\/meetily\.exe'/);
console.log('MAIN-022 build contract passed: short target path, sidecar dir redirected, Release flags kept, no generator override, fresh target, native /O2 gate, dynamic EXE path.');
