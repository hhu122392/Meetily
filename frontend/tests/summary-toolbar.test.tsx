import { afterEach, expect, mock, test } from 'bun:test';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
mock.module('@/i18n',()=>({t:(s:string)=>s,useUiLanguage:()=> 'zh-CN'}));
mock.module('@/lib/analytics',()=>({default:{trackButtonClick:()=>{}}}));
mock.module('@/components/ui/button',()=>({Button:({children,...props}:any)=><button {...props}>{children}</button>}));
const Wrap=({children}:any)=><div>{children}</div>;
mock.module('@/components/ui/dialog',()=>({Dialog:Wrap,DialogContent:Wrap,DialogTrigger:Wrap,DialogTitle:Wrap}));
mock.module('@/components/ui/dropdown-menu',()=>({DropdownMenu:Wrap,DropdownMenuContent:Wrap,DropdownMenuItem:Wrap,DropdownMenuTrigger:Wrap}));
mock.module('@/components/ui/visually-hidden',()=>({VisuallyHidden:Wrap}));
mock.module('@/components/ModelSettingsModal',()=>({ModelSettingsModal:()=> <div data-model-dialog/>}));
mock.module('@/components/templates/TemplateLibrary',()=>({TemplateLibrary:()=> <div data-template-library/>}));
const {SummaryGeneratorButtonGroup}=await import('../src/components/MeetingDetails/SummaryGeneratorButtonGroup');
const {SummaryUpdaterButtonGroup}=await import('../src/components/MeetingDetails/SummaryUpdaterButtonGroup');
let view:ReactTestRenderer;
afterEach(async()=>{await act(async()=>view?.unmount());});
test('上下工具栏只注册一个模型弹窗，生成和停止仍使用原回调',async()=>{
  const generate=mock(async()=>{}),stop=mock(()=>{}),register=mock(()=>{});
  const props:any={modelConfig:{provider:'builtin',model:'qwen'},setModelConfig:()=>{},onSaveModelConfig:async()=>{},onGenerateSummary:generate,onStopGeneration:stop,customPrompt:'会议背景',availableTemplates:[{id:'daily',name:'每日站会'}],selectedTemplate:'daily',onTemplateSelect:()=>{},onOpenModelSettings:register,hasSummary:true};
  const render=(status:string)=><><SummaryGeneratorButtonGroup {...props} summaryStatus={status} layout="toolbar"/><SummaryGeneratorButtonGroup {...props} summaryStatus={status} layout="primary"/></>;
  await act(async()=>{view=create(render('completed'));});
  expect(register).toHaveBeenCalledTimes(1);
  expect(view.root.findAllByProps({'data-model-dialog':true})).toHaveLength(1);
  expect(view.root.findAllByType('button').filter(b=>b.props['aria-label']==='纪要模板：每日站会')).toHaveLength(1);
  await act(async()=>view.root.findByProps({title:'Regenerate AI Summary'}).props.onClick());
  expect(generate).toHaveBeenCalledWith('会议背景');
  await act(async()=>view.update(render('summarizing')));
  await act(async()=>view.root.findByProps({title:'Stop summary generation'}).props.onClick());
  expect(stop).toHaveBeenCalledTimes(1);
});
test('无修改时只显示复制，修改或保存中显示保存按钮',async()=>{
  const copy=mock(async()=>{}),save=mock(async()=>{});
  const render=(dirty:boolean,saving=false)=><SummaryUpdaterButtonGroup isDirty={dirty} isSaving={saving} onCopy={copy} onSave={save}/>;
  await act(async()=>{view=create(render(false));});
  expect(view.root.findAllByType('button')).toHaveLength(1);
  await act(async()=>view.root.findByType('button').props.onClick());expect(copy).toHaveBeenCalledTimes(1);
  await act(async()=>view.update(render(true)));
  await act(async()=>view.root.findAllByType('button').find(b=>b.props['aria-label']==='Save Changes')!.props.onClick());expect(save).toHaveBeenCalledTimes(1);
  await act(async()=>view.update(render(false,true)));
  expect(view.root.findAllByType('button').find(b=>b.props['aria-label']==='Saving')!.props.disabled).toBe(true);
});
